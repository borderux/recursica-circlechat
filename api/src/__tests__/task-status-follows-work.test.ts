import { describe, it, expect } from "vitest";
import { isPartOfSeveral, statusAfterAgentWork } from "../agents/task-status-follows-work.js";
import { SUMMARY_MAX, isTitleLine, leadOf, splitLongReply } from "../agents/long-reply.js";

// One morning's runs, with names made generic. After the instruction for an assigned task stopped
// saying "move it to in_progress", no agent changed a task's status: a transcript writer delivered
// its transcript as an 8,619-character reply, saved as reply.md on the task, and the task stayed
// in Backlog; a designer wrote a page for a task that also stayed in Backlog. The transcript's
// comment showed only the two-line "synthetic" banner, so the task looked empty.
const TRANSCRIPT = `⚠️ SYNTHETIC — generated by Writer. Not real research.
No real person said any of this. Do not analyze as client data.

DesignTool Insights — interview 1 of 1 — Researcher and Maya Patel — 10 min

Researcher  00:00:05
Thanks for meeting today, Maya. Just a quick heads-up: I'm recording this for research purposes. Is that okay?

Maya Patel  00:00:12
Sure, go ahead.
${"\nResearcher  00:01:00\nTell me about the last time your team picked a design tool.\n\nMaya Patel  00:01:20\nWe compared three, and the deciding factor was how it handled shared components.\n".repeat(40)}`;

describe("a task's status follows its assignee's work", () => {
  it("the morning's transcript, a deliverable on a task in Backlog, moves the task to Review", () => {
    expect(statusAfterAgentWork("backlog", { deliverable: true, text: TRANSCRIPT })).toBe("review");
  });

  it("a first comment or file that is not a deliverable moves Backlog to In progress", () => {
    expect(statusAfterAgentWork("backlog", { deliverable: false, text: "Three questions before I start: who is on a team, …" })).toBe("in_progress");
  });

  it("a deliverable on a task in progress moves it to Review", () => {
    expect(statusAfterAgentWork("in_progress", { deliverable: true, text: "Page attached." })).toBe("review");
  });

  it("one part of several stays In progress, so the next parts can still land", () => {
    const first = TRANSCRIPT.replace("interview 1 of 1", "interview 1 of 3");
    expect(isPartOfSeveral(first)).toBe(true);
    expect(isPartOfSeveral(TRANSCRIPT)).toBe(false);
    expect(statusAfterAgentWork("backlog", { deliverable: true, text: first })).toBe("in_progress");
    expect(statusAfterAgentWork("in_progress", { deliverable: true, text: first })).toBeNull();
    expect(statusAfterAgentWork("in_progress", { deliverable: true, text: TRANSCRIPT.replace("interview 1 of 1", "interview 3 of 3") })).toBe("review");
  });

  it("never moves a task backwards, and never touches Done, Blocked or Cancelled", () => {
    expect(statusAfterAgentWork("review", { deliverable: false })).toBeNull();
    expect(statusAfterAgentWork("review", { deliverable: true })).toBeNull();
    expect(statusAfterAgentWork("in_progress", { deliverable: false })).toBeNull();
    for (const s of ["done", "blocked", "cancelled", "something_new"]) {
      expect(statusAfterAgentWork(s, { deliverable: true })).toBeNull();
      expect(statusAfterAgentWork(s, { deliverable: false })).toBeNull();
    }
  });
});

describe("a long reply's post keeps its title", () => {
  it("the morning's transcript: the post shows the banner and the title line, and the file holds it all", () => {
    const split = splitLongReply(TRANSCRIPT, SUMMARY_MAX);
    expect(split.file?.text).toBe(TRANSCRIPT.endsWith("\n") ? TRANSCRIPT : `${TRANSCRIPT}\n`);
    expect(split.body.startsWith("⚠️ SYNTHETIC — generated by Writer. Not real research.\nNo real person said any of this. Do not analyze as client data.\n\nDesignTool Insights — interview 1 of 1 — Researcher and Maya Patel — 10 min\n\n_The full text (")).toBe(true);
    expect(split.body).toMatch(/is attached as reply\.md\._$/);
    expect(split.body.length).toBeLessThanOrEqual(SUMMARY_MAX);
    expect(split.body).not.toContain("Researcher  00:00:05");
  });

  it("knows a title line from a sentence, a list item, a warning or a speaker line", () => {
    expect(isTitleLine("DesignTool Insights — interview 1 of 1 — Researcher and Maya Patel — 10 min")).toBe(true);
    expect(isTitleLine("## Team page brief")).toBe(true);
    expect(isTitleLine("No real person said any of this. Do not analyze as client data.")).toBe(false);
    expect(isTitleLine("⚠️ SYNTHETIC — generated by Writer")).toBe(false);
    expect(isTitleLine("Researcher  00:00:05")).toBe(false);
    expect(isTitleLine("- a list item")).toBe(false);
    expect(isTitleLine("Here is what I built:")).toBe(false);
  });

  it("keeps only the first paragraph when it already has a title, or the next one opens with a sentence", () => {
    expect(leadOf("## Brief\nThe page shows one team.\n\n## Routes\n/team")).toBe("## Brief\nThe page shows one team.");
    expect(leadOf("Backend is live on port 3000. Health returns 200.\n\nDetails: lots more.")).toBe("Backend is live on port 3000. Health returns 200.");
    expect(leadOf("I built the page.\n\nResearcher  00:00:05\nHello.")).toBe("I built the page.");
  });
});
